"""Download the real documents of the corpus into data/raw/<group>/ and record them in data/raw/sources.jsonl.

    python scripts/fetch_corpus.py           # download what is missing
    python scripts/fetch_corpus.py --force   # download everything again

Manual documents (ILO NATLEX PDFs) are only checked and copied from data/manual/.
"""
import argparse
import hashlib
import json
import shutil
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import requests
import yaml

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw"
MANUAL = ROOT / "data" / "manual"
HEADERS = {"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) hr-rag course project"}
PAUSE_S = 2.0   # be polite to government sites


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def fetch(url: str, attempts: int = 3) -> bytes:
    for i in range(attempts):
        try:
            r = requests.get(url, headers=HEADERS, timeout=60)
            r.raise_for_status()
            return r.content
        except requests.RequestException:
            if i == attempts - 1:
                raise
            time.sleep(2 ** i * 3)
    raise RuntimeError("unreachable")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()
    sources = yaml.safe_load((ROOT / "data" / "sources.yaml").read_text(encoding="utf-8"))
    records, failed = [], []
    for group, items in sources.items():
        if group == "company":          # generated by make_company_docs.py, nothing to download
            continue
        for s in items:
            now = datetime.now(timezone.utc).isoformat(timespec="seconds")
            if group == "manual":
                src = next((p for p in MANUAL.glob("*.pdf") if p.name.endswith(s["file"])), None)
                if src is None:
                    print(f"  MISSING manual file {s['file']} -> download it from {s['url']} into data/manual/")
                    failed.append(s["id"])
                    continue
                out = RAW / group / f"{s['id']}.pdf"
                out.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(src, out)
                data = out.read_bytes()
            else:
                out = RAW / group / f"{s['id']}.html"
                out.parent.mkdir(parents=True, exist_ok=True)
                if out.exists() and not args.force:
                    data = out.read_bytes()
                else:
                    try:
                        data = fetch(s["url"])
                    except Exception as e:  # one dead link must not stop the corpus
                        print(f"  FAILED {s['id']}: {type(e).__name__}: {e}")
                        failed.append(s["id"])
                        continue
                    out.write_bytes(data)
                    time.sleep(PAUSE_S)
            records.append({"id": s["id"], "group": group, "lang": s["lang"], "version": str(s["version"]),
                            "url": s["url"], "title": s["title"], "path": out.relative_to(ROOT).as_posix(),
                            "bytes": len(data), "raw_hash": sha256(data), "fetched_at": now})
            print(f"  ok {group:<9} {s['id']:<22} {len(data):>9,} B")
    (RAW / "sources.jsonl").write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in records) + "\n",
                                      encoding="utf-8")
    print(f"\n{len(records)} documents, {len(failed)} failed: {failed}")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
